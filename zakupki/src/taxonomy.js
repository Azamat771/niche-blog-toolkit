/**
 * Определяет нишу закупки.
 * @returns {{ key: string, label: string, source: 'okpd'|'keyword'|'none' }}
 */
function classifyNiche(record) {
  const codes = Array.isArray(record.okpd) ? record.okpd : [];
  for (const code of codes) {
    const division = String(code).slice(0, 2);
    const label = OKPD_DIVISIONS[division] || OKPD_DIVISIONS[String(Number(division))];
    if (label) return { key: `OKPD.${division}`, label, source: 'okpd' };
  }

  const text = record.purchaseObject || '';
  for (const bucket of KEYWORD_BUCKETS) {
    if (bucket.patterns.some((p) => p.test(text))) {
      return { key: bucket.key, label: bucket.label, source: 'keyword' };
    }
  }

  return { key: 'UNCLASSIFIED', label: 'Без классификации', source: 'none' };
}

